const CYRILLIC_MAP: Record<string, string> = {
  а: "a",
  б: "b",
  в: "v",
  г: "g",
  д: "d",
  е: "e",
  ё: "e",
  ж: "zh",
  з: "z",
  и: "i",
  й: "y",
  к: "k",
  л: "l",
  м: "m",
  н: "n",
  о: "o",
  п: "p",
  р: "r",
  с: "s",
  т: "t",
  у: "u",
  ф: "f",
  х: "h",
  ц: "ts",
  ч: "ch",
  ш: "sh",
  щ: "sch",
  ъ: "",
  ы: "y",
  ь: "",
  э: "e",
  ю: "yu",
  я: "ya",
};

function transliterateChar(char: string): string {
  const lower = char.toLowerCase();
  if (CYRILLIC_MAP[lower] !== undefined) {
    return CYRILLIC_MAP[lower]!;
  }
  return lower;
}

/** Slugify article title: lowercase, simple translit, hyphen-separated. */
export function slugifyTitle(title: string): string {
  const normalized = title
    .trim()
    .split("")
    .map((ch) => transliterateChar(ch))
    .join("");

  return normalized
    .toLowerCase()
    .replace(/[^a-z0-9\s-]/g, "")
    .replace(/\s+/g, "-")
    .replace(/-+/g, "-")
    .replace(/^-|-$/g, "");
}
